const MB = 1024 ** 2;
const config = {
  clientId: 'client-id',
  clientSecret: 'client-secret',
  timeoutMs: 5_000,
};
const observer: SocialObserverPort = {
  providerCall: () => {},
  publication: () => {},
  tokenRefresh: () => {},
};

const scratch: ScratchSpacePort = {
  async withDirectory(fn) {
    const dir = await mkdtemp(join(tmpdir(), 'x-adapter-'));
    try {
      return await fn(dir);
    } finally {
      await rm(dir, { recursive: true, force: true });
    }
  },
};

/** Storage whose objects are generated bytes of the requested size, keyed `name:size`. */
const storage = {
  downloadToFile: async (key: string, path: string) => {
    const size = Number(key.split(':')[1] ?? '16');
    await writeFile(path, Buffer.alloc(size, 7));
  },
} as unknown as StoragePort;

const adapter = (overrides: Partial<typeof config> = {}) =>
  new XSocialAdapter(
    { ...config, ...overrides },
    observer,
    new MediaFiles(storage, scratch),
  );

const account: AuthorizedAccount = {
  connectionId: 'conn-1',
  churchId: 'church-1',
  platform: 'x',
  providerAccountId: 'user-1',
  accountName: '@church',
  scopes: [],
  metadata: { userId: 'user-1', username: 'church' },
  accessToken: 'access-secret',
  refreshToken: 'refresh-secret',
};

const publishInput = (overrides: Partial<PublishInput> = {}): PublishInput => ({
  platform: 'x',
  account,
  idempotencyKey: 'pub-1',
  text: 'Sunday sermon',
  media: [],
  settings: {},
  ...overrides,
});

const image = (key: string) => ({
  type: 'image' as const,
  url: 'https://cdn.example/i.png',
  objectKey: key,
  mimeType: 'image/png',
});
const video = (key: string) => ({
  type: 'video' as const,
  url: 'https://cdn.example/v.mp4',
  objectKey: key,
  mimeType: 'video/mp4',
});

type Route = {
  match: (url: string, init: RequestInit) => boolean;
  status: number;
  body: unknown;
  headers?: Record<string, string>;
};

const json = (
  status: number,
  body: unknown,
  headers: Record<string, string> = {},
) =>
  new Response(body === undefined ? null : JSON.stringify(body), {
    status,
    headers: {
      'content-type': 'application/json',
      'x-transaction-id': 'tx-1',
      ...headers,
    },
  });

/** Stubs fetch with ordered routes (first match wins) and records every call. */
const stubFetch = (routes: Route[]) => {
  const fetchMock = vi.fn(async (url: string, init: RequestInit = {}) => {
    const route = routes.find((candidate) => candidate.match(url, init));
    if (!route)
      throw new Error(`Unexpected request ${init.method ?? 'GET'} ${url}`);
    return json(route.status, route.body, route.headers);
  });
  vi.stubGlobal('fetch', fetchMock);
  return fetchMock;
};

const on = (
  method: string,
  path: string,
  status: number,
  body: unknown,
  headers?: Record<string, string>,
): Route => ({
  match: (url, init) =>
    (init.method ?? 'GET') === method && new URL(url).pathname === path,
  status,
  body,
  headers,
});

/** Recorded requests, optionally only those to `path`. */
const callsTo = (fetchMock: ReturnType<typeof stubFetch>, path?: string) =>
  fetchMock.mock.calls
    .filter(([url]) => !path || new URL(url).pathname === path)
    .map(([url, init]) => ({ url, init: init ?? {} }));

const bodyText = (init: RequestInit): string => {
  if (typeof init.body === 'string') return init.body;
  if (init.body instanceof URLSearchParams) return init.body.toString();
  throw new Error('Expected a string or form body');
};
const headersOf = (init: RequestInit) => init.headers as Record<string, string>;

const rejection = async (
  promise: Promise<unknown>,
): Promise<SocialProviderError> => {
  const error = await promise.then(
    () => {
      throw new Error('expected a rejection');
    },
    (caught: unknown) => caught,
  );
  expect(error).toBeInstanceOf(SocialProviderError);
  return error as SocialProviderError;
};

describe('XSocialAdapter', () => {
  afterEach(() => vi.unstubAllGlobals());

  describe('OAuth', () => {
    it('builds an authorization URL with a PKCE S256 challenge, the scopes and the state', async () => {
      const verifier = 'v'.repeat(64);
      const url = new URL(
        await adapter().getAuthorizationUrl({
          state: 'state-1',
          redirectUri: 'https://app.example/callback',
          platforms: ['x'],
          codeVerifier: verifier,
        }),
      );
      expect(url.origin + url.pathname).toBe(
        'https://x.com/i/oauth2/authorize',
      );
      const params = url.searchParams;
      expect(params.get('response_type')).toBe('code');
      expect(params.get('client_id')).toBe('client-id');
      expect(params.get('state')).toBe('state-1');
      expect(params.get('code_challenge')).toBe(pkceChallenge(verifier));
      expect(params.get('code_challenge_method')).toBe('S256');
      expect(params.get('scope')?.split(' ')).toEqual(
        expect.arrayContaining([
          'tweet.read',
          'tweet.write',
          'users.read',
          'offline.access',
          'media.write',
        ]),
      );
      expect(url.toString()).not.toContain(verifier);
    });

    it('exchanges the code with Basic auth and the code_verifier, then reads the user', async () => {
      const fetchMock = stubFetch([
        on('POST', '/2/oauth2/token', 200, {
          token_type: 'bearer',
          access_token: 'new-access',
          refresh_token: 'new-refresh',
          expires_in: 7200,
          scope: 'tweet.read tweet.write users.read offline.access media.write',
        }),
        on('GET', '/2/users/me', 200, {
          data: {
            id: '42',
            username: 'gracechurch',
            name: 'Grace',
            profile_image_url: 'https://pbs/avatar.jpg',
          },
        }),
      ]);
      const { accounts } = await adapter().exchangeAuthorizationCode({
        code: 'code-1',
        redirectUri: 'https://app.example/callback',
        codeVerifier: 'verifier-1',
        platforms: ['x'],
      });

      const { init: tokenInit } = callsTo(fetchMock, '/2/oauth2/token')[0]!;
      const headers = headersOf(tokenInit);
      expect(headers.Authorization).toBe(
        `Basic ${Buffer.from('client-id:client-secret').toString('base64')}`,
      );
      const body = new URLSearchParams(bodyText(tokenInit));
      expect(body.get('grant_type')).toBe('authorization_code');
      expect(body.get('code')).toBe('code-1');
      expect(body.get('code_verifier')).toBe('verifier-1');
      expect(body.get('redirect_uri')).toBe('https://app.example/callback');

      const { url: meUrl, init: meInit } = callsTo(
        fetchMock,
        '/2/users/me',
      )[0]!;
      expect(new URL(meUrl).searchParams.get('user.fields')).toBe(
        'profile_image_url,username,name',
      );
      expect(headersOf(meInit).Authorization).toBe('Bearer new-access');

      expect(accounts).toEqual([
        expect.objectContaining({
          platform: 'x',
          providerAccountId: '42',
          accountName: '@gracechurch',
          avatarUrl: 'https://pbs/avatar.jpg',
          accessToken: 'new-access',
          refreshToken: 'new-refresh',
          metadata: { userId: '42', username: 'gracechurch' },
        }),
      ]);
      expect(accounts[0]?.tokenExpiresAt).toBeInstanceOf(Date);
    });

    it('returns the rotated refresh token on refresh', async () => {
      const fetchMock = stubFetch([
        on('POST', '/2/oauth2/token', 200, {
          token_type: 'bearer',
          access_token: 'access-2',
          refresh_token: 'refresh-2',
          expires_in: 7200,
          scope: 'tweet.read tweet.write',
        }),
      ]);
      const result = await adapter().refreshConnection(account);
      expect(result).toMatchObject({
        accessToken: 'access-2',
        refreshToken: 'refresh-2',
      });
      const { init } = callsTo(fetchMock)[0]!;
      const body = new URLSearchParams(bodyText(init));
      expect(body.get('grant_type')).toBe('refresh_token');
      expect(body.get('refresh_token')).toBe('refresh-secret');
      expect(headersOf(init).Authorization).toMatch(/^Basic /);
    });

    it('maps a rejected refresh token to AUTH_EXPIRED and returns null without one', async () => {
      stubFetch([
        on('POST', '/2/oauth2/token', 400, {
          error: 'invalid_request',
          error_description: 'Value passed for the token was invalid.',
        }),
      ]);
      const error = await rejection(adapter().refreshConnection(account));
      expect(error.code).toBe('AUTH_EXPIRED');
      expect(error.message).not.toContain('refresh-secret');
      expect(
        await adapter().refreshConnection({
          ...account,
          refreshToken: undefined,
        }),
      ).toBeNull();
    });

    it('revokes best effort, even when X rejects the token', async () => {
      const fetchMock = stubFetch([
        on('POST', '/2/oauth2/revoke', 400, { error: 'invalid_request' }),
      ]);
      await expect(
        adapter().revokeConnection(account),
      ).resolves.toBeUndefined();
      const hints = callsTo(fetchMock).map(({ init }) =>
        new URLSearchParams(bodyText(init)).get('token_type_hint'),
      );
      expect(hints).toEqual(['refresh_token', 'access_token']);
    });
  });

  describe('publish', () => {
    it('publishes a text-only post with one decisive call', async () => {
      const fetchMock = stubFetch([
        on('POST', '/2/tweets', 201, {
          data: { id: '1001', text: 'Sunday sermon' },
        }),
      ]);
      const outcome = await adapter().publish(publishInput());
      expect(outcome).toEqual({
        status: 'published',
        providerPostId: '1001',
        permalink: 'https://x.com/church/status/1001',
      });
      expect(fetchMock).toHaveBeenCalledTimes(1);
      const { init } = callsTo(fetchMock)[0]!;
      expect(JSON.parse(bodyText(init))).toEqual({ text: 'Sunday sermon' });
      expect(headersOf(init).Authorization).toBe('Bearer access-secret');
    });

    it('uploads images, then posts with their media ids', async () => {
      let next = 0;
      const fetchMock = stubFetch([
        {
          match: (url, init) =>
            init.method === 'POST' &&
            new URL(url).pathname === '/2/media/upload',
          status: 200,
          get body() {
            next += 1;
            return { data: { id: `m${next}` } };
          },
        },
        on('POST', '/2/tweets', 201, { data: { id: '1002' } }),
      ]);
      const outcome = await adapter().publish(
        publishInput({ media: [image('a.png:1024'), image('b.png:2048')] }),
      );
      expect(outcome).toMatchObject({
        status: 'published',
        providerPostId: '1002',
      });

      const uploads = callsTo(fetchMock, '/2/media/upload');
      expect(uploads).toHaveLength(2);
      const form = uploads[0]!.init.body as FormData;
      expect(form.get('media_category')).toBe('tweet_image');
      expect((form.get('media') as Blob).size).toBe(1024);

      const { init: postInit } = callsTo(fetchMock, '/2/tweets')[0]!;
      expect(JSON.parse(bodyText(postInit))).toEqual({
        text: 'Sunday sermon',
        media: { media_ids: ['m1', 'm2'] },
      });
    });

    it('rejects an oversized image before calling X', async () => {
      const fetchMock = stubFetch([]);
      const error = await rejection(
        adapter().publish(
          publishInput({ media: [image(`big.png:${6 * MB}`)] }),
        ),
      );
      expect(error).toMatchObject({
        code: 'INVALID_MEDIA',
        outcome: 'not_published',
      });
      expect(fetchMock).not.toHaveBeenCalled();
    });

    it('uploads a video in segments and reports processing while X transcodes it', async () => {
      const size = 9 * MB; // 4 MiB + 4 MiB + 1 MiB
      const fetchMock = stubFetch([
        on('POST', '/2/media/upload/initialize', 200, {
          data: { id: 'v1', expires_after_secs: 86400 },
        }),
        on('POST', '/2/media/upload/v1/append', 204, undefined),
        on('POST', '/2/media/upload/v1/finalize', 200, {
          data: {
            id: 'v1',
            processing_info: { state: 'pending', check_after_secs: 5 },
          },
        }),
      ]);
      const outcome = await adapter().publish(
        publishInput({ media: [video(`v.mp4:${size}`)] }),
      );
      expect(outcome).toEqual({
        status: 'processing',
        providerRef: 'v1',
        checkAfterSeconds: 5,
        metadata: { mediaIds: ['v1'] },
      });

      const { init: initInit } = callsTo(
        fetchMock,
        '/2/media/upload/initialize',
      )[0]!;
      expect(JSON.parse(bodyText(initInit))).toEqual({
        media_type: 'video/mp4',
        total_bytes: size,
        media_category: 'tweet_video',
      });
      const appends = callsTo(fetchMock, '/2/media/upload/v1/append').map(
        ({ init }) => init.body as FormData,
      );
      expect(appends.map((body) => body.get('segment_index'))).toEqual([
        '0',
        '1',
        '2',
      ]);
      expect(appends.map((body) => (body.get('media') as Blob).size)).toEqual([
        4 * MB,
        4 * MB,
        1 * MB,
      ]);
      expect(callsTo(fetchMock, '/2/media/upload/v1/finalize')).toHaveLength(1);
      expect(callsTo(fetchMock, '/2/tweets')).toHaveLength(0);
    });

    it('posts immediately when the video needs no processing', async () => {
      stubFetch([
        on('POST', '/2/media/upload/initialize', 200, { data: { id: 'v2' } }),
        on('POST', '/2/media/upload/v2/append', 204, undefined),
        on('POST', '/2/media/upload/v2/finalize', 200, {
          data: { id: 'v2', processing_info: { state: 'succeeded' } },
        }),
        on('POST', '/2/tweets', 201, { data: { id: '1003' } }),
      ]);
      expect(
        await adapter().publish(publishInput({ media: [video('v.mp4:2048')] })),
      ).toMatchObject({
        status: 'published',
        providerPostId: '1003',
      });
    });
  });

  describe('checkPublication', () => {
    const checkInput = (): CheckPublicationInput => ({
      ...publishInput({ media: [video('v.mp4:2048')] }),
      providerRef: 'v1',
      providerMetadata: { mediaIds: ['v1'] },
    });

    it('creates the post once processing succeeded', async () => {
      const fetchMock = stubFetch([
        on('GET', '/2/media/upload', 200, {
          data: { id: 'v1', processing_info: { state: 'succeeded' } },
        }),
        on('POST', '/2/tweets', 201, { data: { id: '1004' } }),
      ]);
      expect(await adapter().checkPublication(checkInput())).toMatchObject({
        status: 'published',
        providerPostId: '1004',
        permalink: 'https://x.com/church/status/1004',
      });
      const { url: statusUrl } = callsTo(fetchMock, '/2/media/upload')[0]!;
      const query = new URL(statusUrl).searchParams;
      expect(query.get('command')).toBe('STATUS');
      expect(query.get('media_id')).toBe('v1');
      const { init: postInit } = callsTo(fetchMock, '/2/tweets')[0]!;
      expect(JSON.parse(bodyText(postInit)).media).toEqual({
        media_ids: ['v1'],
      });
    });

    it('keeps waiting while processing is in progress', async () => {
      stubFetch([
        on('GET', '/2/media/upload', 200, {
          data: {
            id: 'v1',
            processing_info: { state: 'in_progress', check_after_secs: 3 },
          },
        }),
      ]);
      expect(await adapter().checkPublication(checkInput())).toMatchObject({
        status: 'processing',
        providerRef: 'v1',
        checkAfterSeconds: 3,
      });
    });

    it('fails with INVALID_MEDIA when processing failed', async () => {
      stubFetch([
        on('GET', '/2/media/upload', 200, {
          data: {
            id: 'v1',
            processing_info: {
              state: 'failed',
              error: { name: 'InvalidMedia', message: 'Unsupported codec' },
            },
          },
        }),
      ]);
      const error = await rejection(adapter().checkPublication(checkInput()));
      expect(error).toMatchObject({
        code: 'INVALID_MEDIA',
        outcome: 'not_published',
        retryable: false,
      });
    });
  });

  describe('error mapping', () => {
    it('maps 401 to AUTH_EXPIRED', async () => {
      stubFetch([
        on('POST', '/2/tweets', 401, {
          title: 'Unauthorized',
          type: 'about:blank',
          status: 401,
          detail: 'Unauthorized',
        }),
      ]);
      const error = await rejection(adapter().publish(publishInput()));
      expect(error).toMatchObject({
        code: 'AUTH_EXPIRED',
        retryable: false,
        providerRequestId: 'tx-1',
      });
      expect(error.message).not.toContain('access-secret');
    });

    it('maps 429 to RATE_LIMITED, retryable, with the reset time in the diagnostic', async () => {
      stubFetch([
        on(
          'POST',
          '/2/tweets',
          429,
          {
            title: 'Too Many Requests',
            detail: 'Too Many Requests',
            status: 429,
          },
          { 'x-rate-limit-reset': '1759500000' },
        ),
      ]);
      const error = await rejection(adapter().publish(publishInput()));
      expect(error).toMatchObject({
        code: 'RATE_LIMITED',
        retryable: true,
        outcome: 'not_published',
      });
      expect(error.message).toContain('1759500000');
    });

    it('treats a 5xx on POST /2/tweets as an unknown outcome that is never retried', async () => {
      stubFetch([
        on('POST', '/2/tweets', 503, {
          title: 'Service Unavailable',
          status: 503,
        }),
      ]);
      const error = await rejection(adapter().publish(publishInput()));
      expect(error).toMatchObject({
        code: 'PROVIDER_UNAVAILABLE',
        outcome: 'unknown',
        retryable: false,
      });
    });

    it('treats a network error during media upload as retryable and not published', async () => {
      vi.stubGlobal(
        'fetch',
        vi.fn(async () => Promise.reject(new TypeError('fetch failed'))),
      );
      const error = await rejection(
        adapter().publish(publishInput({ media: [image('a.png:512')] })),
      );
      expect(error).toMatchObject({
        code: 'PROVIDER_UNAVAILABLE',
        outcome: 'not_published',
        retryable: true,
      });
    });

    it('maps duplicate content to UNSUPPORTED_CONTENT, not published', async () => {
      stubFetch([
        on('POST', '/2/tweets', 403, {
          title: 'Forbidden',
          type: 'about:blank',
          status: 403,
          detail:
            'You are not allowed to create a Tweet with duplicate content.',
        }),
      ]);
      const error = await rejection(adapter().publish(publishInput()));
      expect(error).toMatchObject({
        code: 'UNSUPPORTED_CONTENT',
        outcome: 'not_published',
        retryable: false,
      });
    });

    it('maps other 403s to PERMISSION_DENIED and media 400s to INVALID_MEDIA', async () => {
      stubFetch([
        on('POST', '/2/tweets', 403, {
          title: 'Client Forbidden',
          type: 'https://api.twitter.com/2/problems/client-forbidden',
          detail:
            'This request must be made using an approved developer account.',
        }),
      ]);
      expect((await rejection(adapter().publish(publishInput()))).code).toBe(
        'PERMISSION_DENIED',
      );

      stubFetch([
        on('POST', '/2/media/upload', 400, {
          errors: [{ message: 'media type unrecognized.' }],
        }),
      ]);
      expect(
        (
          await rejection(
            adapter().publish(publishInput({ media: [image('a.png:512')] })),
          )
        ).code,
      ).toBe('INVALID_MEDIA');
    });
  });

  describe('delete and metrics', () => {
    it('deletes a post and treats an already deleted one as success', async () => {
      const fetchMock = stubFetch([
        on('DELETE', '/2/tweets/1001', 200, { data: { deleted: true } }),
      ]);
      await adapter().delete({
        platform: 'x',
        account,
        providerPostId: '1001',
      });
      expect(fetchMock).toHaveBeenCalledTimes(1);
      stubFetch([
        on('DELETE', '/2/tweets/1001', 404, {
          title: 'Not Found Error',
          status: 404,
        }),
      ]);
      await expect(
        adapter().delete({ platform: 'x', account, providerPostId: '1001' }),
      ).resolves.toBeUndefined();
    });

    it('normalises public metrics', async () => {
      stubFetch([
        on('GET', '/2/tweets/1001', 200, {
          data: {
            id: '1001',
            public_metrics: {
              impression_count: 500,
              like_count: 20,
              reply_count: 4,
              retweet_count: 3,
              quote_count: 2,
              bookmark_count: 6,
            },
          },
        }),
      ]);
      expect(
        await adapter().getMetrics({
          platform: 'x',
          account,
          providerPostId: '1001',
        }),
      ).toEqual({
        impressions: 500,
        likes: 20,
        comments: 4,
        shares: 5,
        saves: 6,
      });
    });
  });

  it('describes its capabilities and whether it is configured', async () => {
    const [capabilities] = await adapter().getCapabilities();
    expect(capabilities).toMatchObject({
      platform: 'x',
      configured: true,
      textOnly: true,
      images: true,
      carousel: true,
      video: true,
      maxImages: 4,
      minCarouselImages: 2,
      maxCaptionLength: 280,
      titleRequired: false,
      maxImageBytes: 5 * MB,
      maxVideoBytes: 512 * MB,
      maxVideoDurationSeconds: 140,
    });
    expect(capabilities?.imageContentTypes).toEqual([
      'image/jpeg',
      'image/png',
      'image/webp',
      'image/gif',
    ]);
    const [unconfigured] = await adapter({
      clientSecret: undefined,
    }).getCapabilities();
    expect(unconfigured?.configured).toBe(false);
  });
});
